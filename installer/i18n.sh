t() {
  local -n table="tr_$ui_lang"
  printf '%s' "${table[$1]:-${tr_en[$1]}}"
}

tf() {
  local key=$1
  shift
  # shellcheck disable=SC2059 # the translated text is the format
  printf "$(t "$key")" "$@"
}

